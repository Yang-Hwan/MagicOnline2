using System;
using System.IO;
using System.Text;
using UnityEngine;
namespace Assets.Scripts.Often {
public static class ReplayVisualStateCodec {
public static byte[] Encode(string json){var s=JsonUtility.FromJson<ReplayVisualState>(json);using(var m=new MemoryStream())using(var w=new BinaryWriter(m)){
w.Write(s.id);
w.Write(s.frame);
w.Write(s.sibling);
w.Write(s.active);
w.Write(s.enabled);
w.Write(s.position.x);
w.Write(s.position.y);
w.Write(s.position.z);
w.Write(s.scale.x);
w.Write(s.scale.y);
w.Write(s.scale.z);
w.Write(s.rotation.x);
w.Write(s.rotation.y);
w.Write(s.rotation.z);
w.Write(s.rotation.w);
w.Write(s.anchorMin.x);
w.Write(s.anchorMin.y);
w.Write(s.anchorMax.x);
w.Write(s.anchorMax.y);
w.Write(s.pivot.x);
w.Write(s.pivot.y);
w.Write(s.size.x);
w.Write(s.size.y);
w.Write(s.anchored.x);
w.Write(s.anchored.y);
w.Write(s.color.r);
w.Write(s.color.g);
w.Write(s.color.b);
w.Write(s.color.a);
w.Write(s.canvasTint.r);
w.Write(s.canvasTint.g);
w.Write(s.canvasTint.b);
w.Write(s.canvasTint.a);
w.Write(s.alpha);
w.Write(s.fill);
w.Write(s.particleTime);
w.Write(s.seed);
w.Write(s.emitting);
w.Write(s.text!=null);if(s.text!=null)w.Write(s.text);
w.Write(s.asset!=null);if(s.asset!=null)w.Write(s.asset);
w.Write(s.texture!=null);if(s.texture!=null)w.Write(s.texture);
w.Write(s.geometry!=null);if(s.geometry!=null)w.Write(s.geometry);
w.Write(s.material!=null);if(s.material!=null)w.Write(s.material);
w.Write(s.particles!=null);if(s.particles!=null)w.Write(s.particles);
w.Write(s.uv.x);
w.Write(s.uv.y);
w.Write(s.uv.width);
w.Write(s.uv.height);
return m.ToArray();}}
public static string Decode(byte[] bytes){using(var m=new MemoryStream(bytes))using(var r=new BinaryReader(m)){var s=new ReplayVisualState();
s.id=r.ReadInt32();
s.frame=r.ReadInt32();
s.sibling=r.ReadInt32();
s.active=r.ReadBoolean();
s.enabled=r.ReadBoolean();
s.position=new Vector3(r.ReadSingle(),r.ReadSingle(),r.ReadSingle());
s.scale=new Vector3(r.ReadSingle(),r.ReadSingle(),r.ReadSingle());
s.rotation=new Quaternion(r.ReadSingle(),r.ReadSingle(),r.ReadSingle(),r.ReadSingle());
s.anchorMin=new Vector2(r.ReadSingle(),r.ReadSingle());
s.anchorMax=new Vector2(r.ReadSingle(),r.ReadSingle());
s.pivot=new Vector2(r.ReadSingle(),r.ReadSingle());
s.size=new Vector2(r.ReadSingle(),r.ReadSingle());
s.anchored=new Vector2(r.ReadSingle(),r.ReadSingle());
s.color=new Color(r.ReadSingle(),r.ReadSingle(),r.ReadSingle(),r.ReadSingle());
s.canvasTint=new Color(r.ReadSingle(),r.ReadSingle(),r.ReadSingle(),r.ReadSingle());
s.alpha=r.ReadSingle();
s.fill=r.ReadSingle();
s.particleTime=r.ReadSingle();
s.seed=r.ReadUInt32();
s.emitting=r.ReadBoolean();
s.text=r.ReadBoolean()?r.ReadString():null;
s.asset=r.ReadBoolean()?r.ReadString():null;
s.texture=r.ReadBoolean()?r.ReadString():null;
s.geometry=r.ReadBoolean()?r.ReadString():null;
s.material=r.ReadBoolean()?r.ReadString():null;
s.particles=r.ReadBoolean()?r.ReadString():null;
s.uv=new Rect(r.ReadSingle(),r.ReadSingle(),r.ReadSingle(),r.ReadSingle());
if(m.Position!=m.Length)throw new InvalidDataException("Trailing replay state bytes");return JsonUtility.ToJson(s);}}
}}